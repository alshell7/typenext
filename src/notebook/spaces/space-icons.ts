const BY_ID = new Map(
  SPACE_ICON_GROUPS.flatMap(group => group.icons).map(item => [item.id, item])
)

export const SPACE_ICON_IDS: readonly string[] = [...BY_ID.keys()]

export function spaceIcon(id: string | undefined): LucideIcon | null {
  return (id && BY_ID.get(id)?.icon) || null
}

/** Words in a workspace name, and the icon they suggest. */
const HINTS: [RegExp, string][] = [
  [/\b(work|job|office|business|client|company)/iu, 'briefcase'],
  [/\b(team|shared|group|club|together)/iu, 'users'],
  [/\b(novel|book|story|fiction|chapter|reading)/iu, 'book'],
  [/\b(poem|poetry|verse|journal|diary)/iu, 'feather'],
  [/\b(blog|essay|article|draft|writing)/iu, 'pen'],
  [/\b(school|study|class|course|thesis|university|exam)/iu, 'graduation'],
  [/\b(research|paper|science|lab)/iu, 'microscope'],
  [/\b(code|dev|engineering|software|api|tech)/iu, 'code'],
  [/\b(design|art|studio|draw|sketch)/iu, 'palette'],
  [/\b(photo|picture)/iu, 'camera'],
  [/\b(film|video|script|screen)/iu, 'film'],
  [/\b(music|song|band|lyric)/iu, 'music'],
  [/\b(home|family|kids|house)/iu, 'home'],
  [/\b(personal|me|private|life)/iu, 'heart'],
  [/\b(travel|trip|holiday|vacation)/iu, 'plane'],
  [/\b(recipe|food|cook|kitchen)/iu, 'pizza'],
  [/\b(garden|plant|nature)/iu, 'sprout'],
  [/\b(health|fitness|medical|doctor)/iu, 'stethoscope'],
  [/\b(law|legal|contract)/iu, 'scale'],
  [/\b(idea|brainstorm|think)/iu, 'lightbulb'],
  [/\b(goal|plan|project|okr)/iu, 'target'],
  [/\b(game|play)/iu, 'gamepad'],
  [/\b(startup|launch|side project)/iu, 'rocket'],
  [/\b(handbook|guide|wiki|reference|docs)/iu, 'library'],
]

/** An icon that fits a new workspace's name, or undefined for its initial. */
export function suggestIcon(name: string): string | undefined {
  return HINTS.find(([pattern]) => pattern.test(name))?.[1]
}
