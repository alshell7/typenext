import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'public', 'runtime', 'builtin')
await mkdir(target, { recursive: true })
for (const stem of [
  'ort-wasm-simd-threaded',
  'ort-wasm-simd-threaded.asyncify',
]) {
  for (const extension of ['mjs', 'wasm'])
    await copyFile(
      path.join(
        root,
        'node_modules',
        'onnxruntime-web',
        'dist',
        `${stem}.${extension}`
      ),
      path.join(target, `${stem}.${extension}`)
    )
}
// Remove only the obsolete assets generated by the previous runtime choice.
for (const extension of ['mjs', 'wasm'])
  await rm(path.join(target, `ort-wasm-simd-threaded.jsep.${extension}`), {
    force: true,
  })
const version = JSON.parse(
  await readFile(
    path.join(root, 'node_modules', 'onnxruntime-web', 'package.json'),
    'utf8'
  )
).version
await writeFile(
  path.join(target, 'runtime-version.txt'),
  `Self-hosted ONNX Runtime Web ${version}\nGenerated from the package lock; run npm run prepare:runtime.\n`
)
await copyFile(
  path.join(root, 'public', 'notices', 'ONNXRuntime-LICENSE.txt'),
  path.join(target, 'LICENSE')
)
console.log(`Prepared bundled offline inference runtime (${version}).`)
